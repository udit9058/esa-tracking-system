export function getLiveFleet() {
  try {
    const raw = localStorage.getItem(FLEET_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch {
    // ignore
  }
  localStorage.setItem(FLEET_STORAGE_KEY, JSON.stringify(INITIAL_BUS_FLEET));
  return INITIAL_BUS_FLEET;
}

export function saveLiveFleet(updatedFleet) {
  localStorage.setItem(FLEET_STORAGE_KEY, JSON.stringify(updatedFleet));
  return updatedFleet;
}

export function getProvisionedUsers() {
  try {
    const raw = localStorage.getItem(USERS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        const seededGuards = INITIAL_ROSTER_USERS.filter((user) => user.role === 'guard');
        const missingGuards = seededGuards.filter(
          (guard) =>
            !parsed.some(
              (user) =>
                String(user.phone || '').replace(/\D/g, '') ===
                String(guard.phone).replace(/\D/g, '')
            )
        );

        if (missingGuards.length > 0) {
          const updatedUsers = [...parsed, ...missingGuards];
          localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(updatedUsers));
          return updatedUsers;
        }

        return parsed;
      }
    }
  } catch {
    // ignore
  }
  localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(INITIAL_ROSTER_USERS));
  return INITIAL_ROSTER_USERS;
}

export function saveProvisionedUsers(updatedUsers) {
  localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(updatedUsers));
  return updatedUsers;
}



